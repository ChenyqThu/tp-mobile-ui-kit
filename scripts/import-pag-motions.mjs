fs.mkdirSync(TARGET_DIR, { recursive: true });
fs.mkdirSync(path.dirname(MANIFEST_PATH), { recursive: true });

const entries = [];
for (const spec of MOTION_SPECS) {
  const absSrc = path.join(SOURCE_DIR, spec.src);
  if (!fs.existsSync(absSrc)) {
    throw new Error(`Missing source PAG file: ${absSrc}`);
  }
  const relPath = `${spec.theme}/${spec.name}.pag`;
  const absDest = path.join(TARGET_DIR, relPath);
  fs.mkdirSync(path.dirname(absDest), { recursive: true });
  fs.copyFileSync(absSrc, absDest);
  const bytes = fs.statSync(absDest).size;
  entries.push({
    name: spec.name,
    title: spec.title,
    category: spec.category,
    theme: spec.theme,
    format: 'pag',
    sourceFile: spec.src,
    relPath,
    bytes,
  });
}

